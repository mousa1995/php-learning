<?php

$a = 10;
$b = 5;

var_dump($a == $b);   // equal
var_dump($a != $b);   // not equal
var_dump($a === $b);  // identical
var_dump($a !== $b);  // not identical
var_dump($a > $b);    // greater than
var_dump($a < $b);    // less than
var_dump($a >= $b);   // greater than or equal
var_dump($a <= $b);   // less than or equal